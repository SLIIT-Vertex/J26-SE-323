import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const sourcePath = resolve(root, "docs/adaptive-gamified-learning/mobile-learning-contracts-v1.json");
const outputPath = resolve(root, "frontend/src/features/mobile-learning-flow/api/generated.ts");
const source = readFileSync(sourcePath, "utf8");
const contract = JSON.parse(source);
const expectedPaths = [
  "/api/v1/development/learning-flow/episodes",
  "/api/v1/development/learning-flow/episodes/{episode_id}/before",
  "/api/v1/development/learning-flow/episodes/{episode_id}/support/complete",
  "/api/v1/development/learning-flow/episodes/{episode_id}/support/withdraw",
  "/api/v1/development/learning-flow/episodes/{episode_id}/after/present",
  "/api/v1/development/learning-flow/episodes/{episode_id}/after",
  "/api/v1/development/learning-flow/episodes/{episode_id}/telemetry",
  "/api/v1/development/learning-flow/draft-missions",
  "/api/v1/development/learning-flow/draft-missions/{area_id}",
];

if (contract.contract_version !== "mobile-learning-contracts-v1" || contract.development_only !== true) {
  throw new Error("Unsupported or non-development contract");
}
for (const path of expectedPaths) {
  if (!contract.openapi?.paths?.[path]) throw new Error(`Missing required operation: ${path}`);
}
for (const schemaName of [
  "DraftMissionCatalog",
  "DraftMissionRecord",
  "MathematicsOutcomeSlot",
  "SinhalaDraftItemSlot",
  "HeldOutcomeSlot",
]) {
  if (!contract.openapi?.components?.schemas?.[schemaName]) {
    throw new Error(`Missing required schema: ${schemaName}`);
  }
}

const digest = createHash("sha256").update(source).digest("hex");
const output = `// Generated by scripts/generate-mobile-learning-types.mjs. Do not edit.\n` +
`export const MOBILE_LEARNING_CONTRACT_VERSION = "mobile-learning-contracts-v1" as const;\n` +
`export const MOBILE_LEARNING_CONTRACT_SHA256 = "${digest}" as const;\n` +
`export type UUID = string;\n` +
`export type ExperimentCondition = "baseline" | "proposed";\n` +
`export type MeasurementRole = "practice" | "unsupported_before" | "supported_practice" | "unsupported_after" | "retention";\n` +
`export type AssistanceState = "none" | "active" | "adult" | "tutor" | "unknown";\n` +
`export interface OpenEpisodeRequest { learner_id: UUID; session_id: UUID; grade: 5; medium: "si"; condition: ExperimentCondition; environment: "development" | "test"; allow_draft: true; }\n` +
`export interface AnswerRequest { option_id: string; response_time_ms?: number | null; }\n` +
`export interface SupportCompleteRequest { duration_ms: number; steps_viewed: number; manifest_revision_id: string; grouped_count: number; group_sizes: [number, number]; }\n` +
`export interface WithdrawalAcknowledgementRequest { request_id: UUID; support_revision_id: string; manifest_revision_id: string; all_support_removed: true; answer_revealing_state_cleared: true; input_handlers_cleared: true; }\n` +
`export interface TelemetryEvent { event_id: UUID; sequence: number; version: 1; client_occurred_at: string; payload: Record<string, string | number | boolean>; }\n` +
`export interface TelemetryBatch { batch_id: UUID; first_sequence: number; events: TelemetryEvent[]; }\n` +
`export interface PublicOption { option_id: string; text_si: string; }\n` +
`export interface PresentationManifest { presentation_id: UUID; revision_id: string; measurement_role: MeasurementRole; assistance_state: AssistanceState; prompt_si: string; accessibility_label_si: string; options: PublicOption[]; content_version: string; }\n` +
`export interface HalfSetGameManifest { schema_version: "half-set-manifest-v1"; activity_id: string; revision_id: string; deterministic_seed: number; total_objects: number; group_count: 2; object_label_si: string; instruction_si: string; }\n` +
`export interface SupportView { scaffold_id: string; revision_id: string; scaffold_type: "visual_guidance" | "worked_parallel_example" | "step_by_step_guidance"; title_si: string; body_si: string[]; visual_alt_text_si: string | null; maximum_steps: number; game_manifest: HalfSetGameManifest; }\n` +
`export interface ParticipationReward { points: number; reason: string; }\n` +
`export interface ChildEpisodeResponse { episode_id: UUID; status: string; manifest: PresentationManifest | null; support: SupportView | null; reward: ParticipationReward | null; }\n` +
`export interface TelemetryAcknowledgement { accepted: number; duplicates: number; next_sequence: number; }\n` +
`export type DraftTemplateId = "market_mission" | "half_set" | "pattern_temple" | "parcel_workshop" | "word_workshop" | "story_studio" | "eco_explorer";\n` +
`export interface MathematicsOutcomeSlot { node_id: string; parent_area_id: string; trace_competency_id: string; supplied_area_match: boolean; confidence: "medium"; draft_item: true; publication_status: "blocked"; item_text: string; }\n` +
`export interface SinhalaDraftItemSlot { node_id: string; parent_area_id: string; confidence: "high"; draft_item: true; publication_status: "blocked"; area_match: boolean; item_text: string; }\n` +
`export interface HeldOutcomeSlot { node_id: string; parent_area_id: string; confidence: "low"; held: true; draft_item: false; publication_status: "blocked"; traced_text: string; child_question: null; }\n` +
`export interface DraftMissionRecord { area_id: string; cited_node_id: string; template_id: DraftTemplateId; development_only: true; publication_status: "blocked"; outcome_slots: MathematicsOutcomeSlot[]; draft_item_slots: SinhalaDraftItemSlot[]; held_slots: HeldOutcomeSlot[]; }\n` +
`export interface DraftMissionCatalog { package_version: "grade5-draft-mission-catalog-v1"; development_only: true; publication_status: "blocked"; missions: DraftMissionRecord[]; }\n`;

const checkedIn = readFileSync(outputPath, "utf8");
if (process.argv.includes("--self-test-drift")) {
  process.exit(`${checkedIn}\n// deliberate drift` === output ? 1 : 0);
}
if (process.argv.includes("--check")) {
  process.exit(checkedIn === output ? 0 : 1);
}
writeFileSync(outputPath, output);
