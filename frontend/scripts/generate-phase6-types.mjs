import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const sourcePath = resolve(root, "docs/adaptive-gamified-learning/phase6-mobile-contracts-v1.json");
const outputPath = resolve(root, "frontend/src/features/phase7/api/generated.ts");
const source = readFileSync(sourcePath, "utf8");
const contract = JSON.parse(source);
const expectedPaths = [
  "/api/v1/development/phase6/episodes",
  "/api/v1/development/phase6/episodes/{episode_id}/before",
  "/api/v1/development/phase6/episodes/{episode_id}/support/complete",
  "/api/v1/development/phase6/episodes/{episode_id}/support/withdraw",
  "/api/v1/development/phase6/episodes/{episode_id}/after/present",
  "/api/v1/development/phase6/episodes/{episode_id}/after",
  "/api/v1/development/phase6/episodes/{episode_id}/telemetry",
];

if (contract.contract_version !== "phase6-mobile-contracts-v1" || contract.development_only !== true) {
  throw new Error("Unsupported or non-development contract");
}
for (const path of expectedPaths) {
  if (!contract.openapi?.paths?.[path]) throw new Error(`Missing required operation: ${path}`);
}

const digest = createHash("sha256").update(source).digest("hex");
const output = `// Generated by scripts/generate-phase6-types.mjs. Do not edit.\n` +
`export const PHASE6_CONTRACT_VERSION = "phase6-mobile-contracts-v1" as const;\n` +
`export const PHASE6_CONTRACT_SHA256 = "${digest}" as const;\n` +
`export type UUID = string;\n` +
`export type ExperimentCondition = "baseline" | "proposed";\n` +
`export type MeasurementRole = "practice" | "unsupported_before" | "supported_practice" | "unsupported_after" | "retention";\n` +
`export type AssistanceState = "none" | "active" | "adult" | "tutor" | "unknown";\n` +
`export interface OpenEpisodeRequest { learner_id: UUID; session_id: UUID; grade: 5; medium: "si"; condition: ExperimentCondition; environment: "development" | "test"; allow_draft: true; }\n` +
`export interface AnswerRequest { option_id: string; }\n` +
`export interface SupportCompleteRequest { duration_ms: number; steps_viewed: number; }\n` +
`export interface TelemetryEvent { event_id: UUID; sequence: number; version: 1; payload: Record<string, string | number | boolean>; }\n` +
`export interface TelemetryBatch { batch_id: UUID; first_sequence: number; events: TelemetryEvent[]; }\n` +
`export interface PublicOption { option_id: string; text_si: string; }\n` +
`export interface PresentationManifest { presentation_id: UUID; revision_id: string; measurement_role: MeasurementRole; assistance_state: AssistanceState; prompt_si: string; accessibility_label_si: string; options: PublicOption[]; content_version: string; }\n` +
`export interface HalfSetGameManifest { schema_version: "half-set-manifest-v1"; activity_id: string; revision_id: string; deterministic_seed: number; total_objects: number; group_count: 2; object_label_si: string; instruction_si: string; }\n` +
`export interface SupportView { scaffold_id: string; revision_id: string; scaffold_type: "visual_guidance" | "worked_parallel_example" | "step_by_step_guidance"; title_si: string; body_si: string[]; visual_alt_text_si: string | null; maximum_steps: number; game_manifest: HalfSetGameManifest; }\n` +
`export interface ParticipationReward { points: number; reason: string; }\n` +
`export interface ChildEpisodeResponse { episode_id: UUID; status: string; manifest: PresentationManifest | null; support: SupportView | null; reward: ParticipationReward | null; }\n` +
`export interface TelemetryAcknowledgement { accepted: number; duplicates: number; next_sequence: number; }\n`;

if (process.argv.includes("--check")) {
  process.exit(readFileSync(outputPath, "utf8") === output ? 0 : 1);
}
writeFileSync(outputPath, output);
