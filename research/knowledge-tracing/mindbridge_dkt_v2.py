# Cell 4 — baselines
def report(name, y, p, src):
    y, p, src = np.asarray(y), np.asarray(p, dtype=float), np.asarray(src)
    out = {'method': name, 'AUC_all': roc_auc_score(y, p)}
    out['AUC_paper'] = roc_auc_score(y[src == PAPER], p[src == PAPER])
    out['AUC_digital'] = roc_auc_score(y[src == DIGITAL], p[src == DIGITAL])
    return out

