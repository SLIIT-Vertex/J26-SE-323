"""## Step 4 — Build the sequences
For every student we keep, per step: the skill, source and difficulty of the question, the answer, and the penalty.
The model predicts step t+1 from the history up to step t PLUS the skill/source/difficulty of question t+1.
"""

# Cell 5 — tensors and loaders
import torch
import torch.nn as nn
from torch.utils.data import DataLoader
from torch.nn.utils.rnn import pad_sequence

def make_seqs(user_ids):
    seqs = []
    for uid, g in df[df.user_id.isin(user_ids)].groupby('user_id'):
        seqs.append({
            'skills': torch.tensor(g['skill_id'].values, dtype=torch.long),
            'corrects': torch.tensor(g['correct'].values, dtype=torch.float32),
            'sources': torch.tensor(g['source'].values, dtype=torch.float32),
            'penalties': torch.tensor(g['penalty'].values, dtype=torch.float32),
            'diffs': torch.tensor(g['difficulty'].values / 0.30, dtype=torch.float32),   # scaled to 0..1
        })
    return seqs

def collate(batch):
    keys = ['skills', 'corrects', 'sources', 'penalties', 'diffs']
    out = [pad_sequence([b[k] for b in batch], batch_first=True, padding_value=0) for k in keys]
    lengths = torch.tensor([len(b['skills']) for b in batch])
    mask = torch.arange(out[0].size(1))[None, :] < lengths[:, None]
    return (*out, mask)

train_seqs, val_seqs, test_seqs = make_seqs(train_ids), make_seqs(val_ids), make_seqs(test_ids)
def loader(seqs, shuffle):
    return DataLoader(seqs, batch_size=32, shuffle=shuffle, collate_fn=collate)
val_loader, test_loader = loader(val_seqs, False), loader(test_seqs, False)
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
print("Sequences ready. Device:", device)

"""## Step 5 — Model
GRU reads the history (skill, answer, source, penalty). A small head then combines the GRU state with the
NEXT question's skill, source and difficulty. `use_source=False` hides the source from the model (ablation).
"""

# Cell 6 — model
class MindBridgeDKT(nn.Module):
    def __init__(self, num_skills=NUM_SKILLS, use_source=True, emb=32, hidden=96):
        super().__init__()
        self.use_source = use_source
        self.skill_emb = nn.Embedding(num_skills, emb)
        self.gru = nn.GRU(emb + 3, hidden, num_layers=2, batch_first=True, dropout=0.3)
        self.head = nn.Sequential(nn.Linear(hidden + emb + 2, 64), nn.ReLU(),
                                  nn.Dropout(0.2), nn.Linear(64, 1))

    def forward(self, skills, corrects, sources, penalties, diffs):
        src = sources if self.use_source else torch.zeros_like(sources)
        e = self.skill_emb(skills)
        h, _ = self.gru(torch.cat([e, corrects[..., None], src[..., None], penalties[..., None]], -1))
        q = torch.cat([e[:, 1:], src[:, 1:, None], diffs[:, 1:, None]], -1)   # next question's info
        return self.head(torch.cat([h[:, :-1], q], -1)).squeeze(-1)           # logits for steps 1..T-1

"""## Step 6 — Training and evaluation functions
Loss weights are applied only in training. Evaluation is always unweighted, and reported for all / paper / digital targets.
"""

# Cell 7 — training utilities
bce = nn.BCEWithLogitsLoss(reduction='none')

def to_dev(batch):
    return [t.to(device) for t in batch]

def run_epoch(model, loader_, w_paper, optimizer=None):
    train = optimizer is not None
    model.train(train)
    tot, n = 0.0, 0.0
    ys, ps, ss = [], [], []
    with torch.set_grad_enabled(train):
        for batch in loader_:
            skills, corrects, sources, penalties, diffs, mask = to_dev(batch)
            logits = model(skills, corrects, sources, penalties, diffs)
            y, m, s = corrects[:, 1:], mask[:, 1:], sources[:, 1:]
            # paper answers count w_paper times more in the loss (2.0 for variant C), game answers count 1
            w = torch.where(s == PAPER, torch.tensor(w_paper, device=device), torch.tensor(1.0, device=device)) * m
            loss = (bce(logits, y) * w).sum() / w.sum()
            if train:
                optimizer.zero_grad(); loss.backward()
                nn.utils.clip_grad_norm_(model.parameters(), 1.0); optimizer.step()
            tot += loss.item(); n += 1
            ys.append(y[m].cpu().numpy()); ps.append(torch.sigmoid(logits)[m].detach().cpu().numpy()); ss.append(s[m].cpu().numpy())
    y, p, s = np.concatenate(ys), np.concatenate(ps), np.concatenate(ss)
    return tot / n, y, p, s

def fit_model(use_source, w_paper, seed):
    torch.manual_seed(seed); np.random.seed(seed)
    model = MindBridgeDKT(use_source=use_source).to(device)
    opt = torch.optim.Adam(model.parameters(), lr=2e-3, weight_decay=1e-5)
    tl = DataLoader(train_seqs, batch_size=32, shuffle=True, collate_fn=collate)
    best_auc, best_state, bad = 0.0, None, 0
    for epoch in range(1, MAX_EPOCHS + 1):
        run_epoch(model, tl, w_paper, opt)
        _, y, p, _ = run_epoch(model, val_loader, 1.0)
        auc = roc_auc_score(y, p)
        # early stopping: keep the epoch with the best validation AUC, stop after 6 epochs with no gain
        if auc > best_auc + 1e-4:
            best_auc, best_state, bad = auc, copy.deepcopy(model.state_dict()), 0
        else:
            bad += 1
            if bad >= PATIENCE: break
    model.load_state_dict(best_state)
    return model, best_auc, epoch

