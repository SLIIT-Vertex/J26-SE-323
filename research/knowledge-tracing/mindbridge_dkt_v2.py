"""## Step 8 — Use the model: knowledge state for the paper generator
For one student's history, predict P(correct) on a medium-difficulty PAPER question for every one of the 30 skills.
This is the "true state" vector your knapsack paper generator can use.
"""

# Cell 11 — knowledge-state function
@torch.no_grad()
def knowledge_state(model, skills, corrects, sources, penalties,
                    difficulty=0.15, source=PAPER, min_attempts=3):
    """History arrays (length T) -> {skill_name: {'mastery': P(correct on a paper question of this difficulty) or None,
                                                   'attempts': number of answers in the history}}
    A skill with fewer than `min_attempts` answers is reported as None = UNKNOWN (the model has no basis for it)."""
    model.eval()
    T = len(skills)
    def rep(a, extra, dtype):
        base = torch.tensor(a, dtype=dtype)[None].repeat(NUM_SKILLS, 1)
        return torch.cat([base, torch.full((NUM_SKILLS, 1), extra, dtype=dtype)], 1)
    sk = torch.cat([torch.tensor(skills, dtype=torch.long)[None].repeat(NUM_SKILLS, 1),
                    torch.arange(NUM_SKILLS)[:, None]], 1)                 # extra step = the query skill
    co = rep(corrects, 0.0, torch.float32); so = rep(sources, float(source), torch.float32)
    pe = rep(penalties, 0.0, torch.float32); di = rep(np.zeros(T), difficulty / 0.30, torch.float32)
    logits = model(sk.to(device), co.to(device), so.to(device), pe.to(device), di.to(device))
    probs = torch.sigmoid(logits[:, -1]).cpu().numpy()
    counts = np.bincount(np.asarray(skills, dtype=int), minlength=NUM_SKILLS)
    return {name: {'mastery': round(float(probs[i]), 3) if counts[i] >= min_attempts else None,
                   'attempts': int(counts[i])}
            for i, name in enumerate(CANONICAL_SKILLS)}

