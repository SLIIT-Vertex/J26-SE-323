def theory_for(area_id: str) -> tuple[tuple[str, str], ...]:
    """The area's theory, or nothing for an area (or subject) that has none."""

    if area_id.startswith("G5-AREA-ENG-"):
        # Imported here: the English lessons package also imports from the builders.
        from app.gamification.application.support_builders.lessons.english import (
            theory_for_english,
        )

        return theory_for_english(area_id)
    return MATHEMATICS_THEORY.get(area_id, ())


def rule_for(area_id: str) -> tuple[tuple[str, str], ...]:
    """Only the area's how-to line, for help types that remind rather than teach."""

    return tuple(pair for pair in theory_for(area_id) if pair[0] == RULE)
