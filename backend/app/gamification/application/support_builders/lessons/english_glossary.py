def meaning(word: object) -> tuple[str, str] | None:
    """The Sinhala meaning and picture of an English word or phrase, when the lesson has it."""

    return GLOSSARY.get(str(word or "").strip().lower())


def taught(word: object) -> str:
    """``“Rose” 🌹 = රෝස`` — or just the word, quoted, when it is not in the glossary."""

    text = str(word or "").strip()
    found = meaning(text)
    return f"“{text}” {found[1]} = {found[0]}" if found else f"“{text}”"
