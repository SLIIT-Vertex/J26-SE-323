def build() -> list[dict[str, object]]:
    cases: list[dict[str, object]] = []
    for index, skill_id in enumerate(sorted(SKILL_CASES)):
        test_positions = {(3 * index + offset) % len(FORMS) for offset in range(3)}
        for position, (form, message) in enumerate(zip(FORMS, SKILL_CASES[skill_id], strict=True)):
            cases.append(
                _case(
                    case_id=f"SM2-{skill_id}-{position + 1}",
                    group_id=f"SKILL-{skill_id}-{position + 1}",
                    split="test" if position in test_positions else "development",
                    category="skill-coverage",
                    form=form,
                    message=message,
                    status="MATCHED",
                    skill_id=skill_id,
                    intent="EXPLANATION_REQUEST",
                )
            )

    group_split: dict[str, str] = {}
    category_counts: dict[str, int] = {}
    for number, (
        group,
        category,
        form,
        message,
        status,
        skill,
        intent,
        plausible,
        context,
        active,
    ) in enumerate(INTERACTION_CASES, start=1):
        if group not in group_split:
            count = category_counts.get(category, 0)
            group_split[group] = "development" if count % 2 == 0 else "test"
            category_counts[category] = count + 1
        cases.append(
            _case(
                case_id=f"SM2-INT-{number:02d}",
                group_id=group,
                split=group_split[group],
                category=category,
                form=form,
                message=message,
                status=status,
                skill_id=skill,
                intent=intent,
                plausible=plausible,
                context=context,
                active=active,
            )
        )
    return cases


def _case(
    *,
    case_id: str,
    group_id: str,
    split: str,
    category: str,
    form: str,
    message: str,
    status: str,
    skill_id: str | None,
    intent: str,
    plausible: tuple[str, ...] = (),
    context: tuple[tuple[str, str], ...] = (),
    active: str | None = None,
) -> dict[str, object]:
    case: dict[str, object] = {
        "case_id": case_id,
        "group_id": group_id,
        "split": split,
        "category": category,
        "language": form,
        "learner_message": message,
        "proposed_status": status,
        "proposed_skill_id": skill_id,
        "proposed_intent": intent,
        "provenance": PROVENANCE,
        "label_status": "PROPOSED",
        "review_status": "PENDING",
    }
    if plausible:
        case["proposed_plausible_skill_ids"] = list(plausible)
    if context:
        case["conversation_context"] = [{"role": role, "message": text} for role, text in context]
    if active:
        case["active_skill_id"] = active
    return case


def main() -> int:
    cases = build()
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    corpus_bytes = json.dumps(cases, ensure_ascii=False, sort_keys=True).encode("utf-8")
    header = {
        "dataset_version": "skill-mapper-corpus-v2",
        "provenance": PROVENANCE,
        "status": (
            "Design-authored proposals only. Not ground truth. Results on this corpus are "
            "diagnostic until qualified language and curriculum review is complete."
        ),
        "split_policy": __doc__.split("Split policy", 1)[1].strip(),
        "content_sha256": hashlib.sha256(corpus_bytes).hexdigest(),
    }
    for split, tuning_allowed in (("development", True), ("test", False)):
        selected = [case for case in cases if case["split"] == split]
        document = {**header, "split": split, "tuning_allowed": tuning_allowed, "cases": selected}
        path = OUTPUT_DIR / f"skill-mapper-corpus-v2-{split}.json"
        path.write_text(json.dumps(document, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")

    review_path = OUTPUT_DIR / "skill-mapper-corpus-v2-review.csv"
    with review_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            [
                "case_id",
                "split",
                "category",
                "language",
                "learner_message",
                "conversation_context",
                "proposed_status",
                "proposed_skill_id",
                "proposed_plausible_skill_ids",
                "reviewer_language_ok",
                "reviewer_corrected_message",
                "reviewer_status",
                "reviewer_skill_id",
                "reviewer_disposition",
                "reviewer_comments",
            ]
        )
        for case in cases:
            context = case.get("conversation_context") or []
            writer.writerow(
                [
                    case["case_id"],
                    case["split"],
                    case["category"],
                    case["language"],
                    case["learner_message"],
                    " | ".join(f"{turn['role']}: {turn['message']}" for turn in context),  # type: ignore[index]
                    case["proposed_status"],
                    case["proposed_skill_id"] or "",
                    ";".join(case.get("proposed_plausible_skill_ids", [])),  # type: ignore[arg-type]
                    "",
                    "",
                    "",
                    "",
                    "",
                    "",
                ]
            )
    print(json.dumps({"cases": len(cases), "sha256": header["content_sha256"]}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
