"""Builds `shared/game_skill_map.json`: which of our 30 skills each of the game's own skills belongs to.

The game keeps finer skills (for example MAT-DIV, or G5-MAT-DIV-WRITTEN-01) that are parts of our 30.
We do not change any of them. This script reads the game's flows and the game's own area data
(`areas.json`, which names the parent skill of every area) and writes two tables:

* `item_skills`: the game's item skill id -> our skill
* `sub_skills`: the game's own skill label -> our skill (only where the two differ)

The knowledge-tracing reader uses the file; it never imports the game. Run this whenever the game
adds or renames a skill, then commit the file. A test fails when the file is out of date.

    python -m scripts.build_game_skill_map          write the file
    python -m scripts.build_game_skill_map --check  exit 1 if the file is out of date
"""

import argparse
import importlib
import inspect
import json
import pkgutil
import sys
from pathlib import Path

FILE_VERSION = 1


def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def default_output() -> Path:
    return repo_root() / "shared" / "game_skill_map.json"


def _our_skills() -> set[str]:
    return set(json.loads((repo_root() / "shared" / "feature_spec.json").read_text(encoding="utf-8"))["skills"])


def _area_parents() -> dict[str, str]:
    path = repo_root() / "data" / "gamification" / "grade5-playable-area-package" / "v1" / "areas.json"
    areas = json.loads(path.read_text(encoding="utf-8"))["areas"]
    return {row["area_id"]: row["universal_skill_id"] for row in areas if row.get("universal_skill_id")}


def _flows() -> list[type]:
    """The game's playable-area flow classes (read only: nothing is instantiated or changed)."""
    package = importlib.import_module("app.gamification.application")
    found: list[type] = []
    for module_info in pkgutil.iter_modules(package.__path__):
        if not module_info.name.endswith("_flow"):
            continue
        module = importlib.import_module(f"app.gamification.application.{module_info.name}")
        for _, cls in inspect.getmembers(module, inspect.isclass):
            if cls.__module__ == module.__name__ and hasattr(cls, "area_id") and hasattr(cls, "skills"):
                found.append(cls)
    return sorted(found, key=lambda cls: (cls.area_id, cls.__name__))


def build() -> dict[str, object]:
    ours = _our_skills()
    parents = _area_parents()
    item_skills: dict[str, str] = {}
    sub_skills: dict[str, str] = {}
    problems: list[str] = []
    for flow in _flows():
        label = str(flow.universal_skill_id)
        # the game's own area data is the authority; a flow that is not in it must already use our id
        parent = parents.get(str(flow.area_id)) or (label if label in ours else None)
        if parent is None or parent not in ours:
            problems.append(f"{flow.__name__} ({flow.area_id}): no parent skill among our 30 for {label!r}")
            continue
        if label != parent and sub_skills.setdefault(label, parent) != parent:
            problems.append(f"{label!r} would map to two different skills")
        for item_skill in flow.skills:
            if item_skills.setdefault(str(item_skill), parent) != parent:
                problems.append(f"item skill {item_skill!r} is in two areas with different parents")
    if problems:
        raise SystemExit("cannot build the skill map:\n  " + "\n  ".join(problems))
    return {
        "version": FILE_VERSION,
        "note": "Generated by backend/scripts/build_game_skill_map.py. Do not edit by hand.",
        "sub_skills": dict(sorted(sub_skills.items())),
        "item_skills": dict(sorted(item_skills.items())),
    }


def render(data: dict[str, object]) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check that the file is up to date")
    parser.add_argument("--output", type=Path, default=default_output())
    args = parser.parse_args(argv)
    text = render(build())
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != text:
            print(f"{args.output} is out of date: run  python -m scripts.build_game_skill_map", file=sys.stderr)
            return 1
        print("the skill map is up to date")
        return 0
    args.output.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
